# This program performs different operations on a full name.

full_name = input("Enter your full name: ")

print("Uppercase:", full_name.upper())
print("Lowercase:", full_name.lower())
print("Reversed:", full_name[::-1])
print("Length:", len(full_name))

# These are three different string methods used in the program.
print("Title Case:", full_name.title())
print("Capitalized:", full_name.capitalize())